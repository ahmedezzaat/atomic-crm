-- Search history for Find leads (what was searched and when, never Google's data)
create table public.lead_searches (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    query text not null,
    results integer not null default 0,
    imported integer not null default 0,
    sales_id bigint
);

alter table public.lead_searches
    add constraint lead_searches_sales_id_fkey foreign key (sales_id) references public.sales(id);
create index lead_searches_query_idx on public.lead_searches (query);

alter table public.lead_searches enable row level security;
create policy "Enable read access for authenticated users" on public.lead_searches for select to authenticated using (true);
grant select on table public.lead_searches to authenticated;
grant all on table public.lead_searches to service_role;
grant all on sequence public.lead_searches_id_seq to service_role;

-- WhatsApp campaigns can send their next batch by themselves every day
alter table public.wa_campaigns
    add column auto_daily boolean not null default false,
    add column send_hour smallint not null default 10,
    add constraint wa_campaigns_send_hour_check check (send_hour between 0 and 23);

-- c.* is expanded when a view is created, so recreate it to pick up the new columns
drop view public.wa_campaigns_summary;
create view public.wa_campaigns_summary with (security_invoker = on) as
select
    c.*,
    count(m.id) as nb_messages,
    count(m.id) filter (where m.status in ('sent', 'delivered', 'read')) as nb_sent,
    count(m.id) filter (where m.status in ('delivered', 'read')) as nb_delivered,
    count(m.id) filter (where m.status = 'read') as nb_read,
    count(m.id) filter (where m.status = 'failed') as nb_failed,
    count(distinct m.phone) filter (where exists (
        select 1 from public.whatsapp_messages r
        where r.phone = m.phone and r.direction = 'in' and r.created_at > m.created_at
    )) as nb_replied
from public.wa_campaigns c
    left join public.whatsapp_messages m on m.campaign_id = c.id and m.direction = 'out'
group by c.id;
grant all on table public.wa_campaigns_summary to authenticated;
grant all on table public.wa_campaigns_summary to service_role;

-- Called every hour by pg_cron: asks the wa_campaign_send function to send the
-- next batch of every automatic campaign whose send hour (Cairo time) it is.
-- The function URL and token are stored by the app (see wa_campaign_send "arm").
create or replace function public.run_wa_auto_campaigns() returns void
    language plpgsql security definer set search_path = ''
as $$
declare
    base_url text;
    token text;
    campaign record;
begin
    select value into base_url from public.integration_secrets where key = 'functions_url';
    select value into token from public.integration_secrets where key = 'cron_token';
    if base_url is null or token is null then
        return;
    end if;
    for campaign in
        select id from public.wa_campaigns
        where auto_daily
          and status <> 'done'
          and template_name <> ''
          and send_hour = extract(hour from (now() at time zone 'Africa/Cairo'))::int
    loop
        perform net.http_post(
            url := base_url || '/wa_campaign_send',
            body := jsonb_build_object('campaign_id', campaign.id, 'cron', true),
            headers := jsonb_build_object('Content-Type', 'application/json', 'x-cron-token', token),
            timeout_milliseconds := 5000
        );
    end loop;
end;
$$;
revoke all on function public.run_wa_auto_campaigns() from public, anon, authenticated;

-- Schedule it. Guarded so a project without pg_cron still deploys (auto-send then stays off).
do $$
begin
    create extension if not exists pg_cron;
    perform cron.unschedule(jobid) from cron.job where jobname = 'wa-auto-campaigns';
    perform cron.schedule('wa-auto-campaigns', '5 * * * *', 'select public.run_wa_auto_campaigns()');
exception when others then
    raise notice 'pg_cron is not available, automatic WhatsApp campaigns stay off: %', sqlerrm;
end
$$;

alter table public.companies
    add column whatsapp_opt_in boolean not null default false,
    add column whatsapp_opted_out boolean not null default false;

create table public.whatsapp_messages (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    company_id bigint,
    phone text not null,
    direction text not null,
    body text not null default '',
    template_name text,
    status text not null default 'queued',
    wa_message_id text,
    error text,
    sales_id bigint,
    constraint whatsapp_messages_direction_check check (direction in ('in', 'out')),
    constraint whatsapp_messages_status_check check (status in ('queued', 'sent', 'delivered', 'read', 'failed', 'received'))
);

alter table public.whatsapp_messages
    add constraint whatsapp_messages_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete set null;

alter table public.whatsapp_messages
    add constraint whatsapp_messages_sales_id_fkey foreign key (sales_id) references public.sales(id);

create index whatsapp_messages_company_id_idx on public.whatsapp_messages (company_id);
create index whatsapp_messages_phone_idx on public.whatsapp_messages (phone);
create unique index whatsapp_messages_wa_message_id_idx on public.whatsapp_messages (wa_message_id) where wa_message_id is not null;

alter table public.whatsapp_messages enable row level security;

-- Staff can read the conversation; all writes go through the server functions
create policy "Enable read access for authenticated users" on public.whatsapp_messages for select to authenticated using (true);

grant select on table public.whatsapp_messages to authenticated;
grant all on table public.whatsapp_messages to service_role;
grant all on sequence public.whatsapp_messages_id_seq to service_role;

-- Quotations: a product/service catalog and quotations made for companies

create table public.products (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    description text not null default '',
    unit_price numeric not null default 0,
    active boolean not null default true
);

create sequence public.quotation_number_seq;

create table public.quotations (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    number text not null unique default '',
    company_id bigint not null,
    contact_id bigint,
    sales_id bigint,
    status text not null default 'draft',
    issue_date date not null default current_date,
    valid_until date,
    currency text not null default 'EGP',
    language text not null default 'en',
    items jsonb not null default '[]'::jsonb,
    total numeric not null default 0,
    notes text not null default '',
    terms text not null default '',
    constraint quotations_status_check check (status in ('draft', 'sent', 'accepted', 'rejected')),
    constraint quotations_language_check check (language in ('en', 'ar')),
    constraint quotations_items_check check (jsonb_typeof(items) = 'array')
);

alter table public.quotations
    add constraint quotations_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete cascade;
alter table public.quotations
    add constraint quotations_contact_id_fkey foreign key (contact_id) references public.contacts(id) on delete set null;
alter table public.quotations
    add constraint quotations_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;

create index quotations_company_id_idx on public.quotations (company_id);

create or replace function public.set_quotation_number() returns trigger
    language plpgsql
    set search_path = public
as $$
begin
    if coalesce(new.number, '') = '' then
        new.number := 'Q-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.quotation_number_seq')::text, 4, '0');
    end if;
    return new;
end;
$$;

create trigger set_quotation_number before insert on public.quotations
    for each row execute function public.set_quotation_number();

alter table public.products enable row level security;
create policy "Enable read access for authenticated users" on public.products for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.products for insert to authenticated with check (true);
create policy "Product Update Policy" on public.products for update to authenticated using (true);
create policy "Product Delete Policy" on public.products for delete to authenticated using (true);

alter table public.quotations enable row level security;
create policy "Enable read access for authenticated users" on public.quotations for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.quotations for insert to authenticated with check (true);
create policy "Quotation Update Policy" on public.quotations for update to authenticated using (true);
create policy "Quotation Delete Policy" on public.quotations for delete to authenticated using (true);

grant all on table public.products to authenticated;
grant all on table public.products to service_role;
grant all on sequence public.products_id_seq to authenticated;
grant all on sequence public.products_id_seq to service_role;
grant all on table public.quotations to authenticated;
grant all on table public.quotations to service_role;
grant all on sequence public.quotations_id_seq to authenticated;
grant all on sequence public.quotations_id_seq to service_role;
grant usage on sequence public.quotation_number_seq to authenticated, service_role;

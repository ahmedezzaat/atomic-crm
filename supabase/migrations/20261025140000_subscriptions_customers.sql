create table public.subscriptions (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    company_id bigint not null,
    product text,
    start_date date not null,
    end_date date not null,
    value numeric not null default 0,
    nb_users integer not null default 0,
    constraint subscriptions_dates_check check (end_date >= start_date)
);

alter table public.subscriptions
    add constraint subscriptions_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete cascade;

create index subscriptions_company_id_idx on public.subscriptions (company_id);

alter table public.subscriptions enable row level security;

create policy "Enable read access for authenticated users" on public.subscriptions for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.subscriptions for insert to authenticated with check (true);
create policy "Subscription Update Policy" on public.subscriptions for update to authenticated using (true);
create policy "Subscription Delete Policy" on public.subscriptions for delete to authenticated using (true);

grant all on table public.subscriptions to anon;
grant all on table public.subscriptions to authenticated;
grant all on table public.subscriptions to service_role;
grant all on sequence public.subscriptions_id_seq to anon;
grant all on sequence public.subscriptions_id_seq to authenticated;
grant all on sequence public.subscriptions_id_seq to service_role;

-- Customers are the companies that have at least one won (non-archived) deal.
create or replace view public.customers_summary with (security_invoker = on) as
select
    c.id,
    c.name,
    c.logo,
    c.city,
    c.phone_number,
    c.sector,
    (select count(*) from public.deals d where d.company_id = c.id and d.stage = 'won' and d.archived_at is null) as nb_won_deals,
    (select count(*) from public.subscriptions s where s.company_id = c.id) as nb_subscriptions,
    (select count(*) from public.subscriptions s where s.company_id = c.id and s.end_date >= current_date) as nb_active_subscriptions,
    coalesce((select sum(s.value) from public.subscriptions s where s.company_id = c.id and s.end_date >= current_date), 0) as active_value,
    coalesce((select sum(s.nb_users) from public.subscriptions s where s.company_id = c.id and s.end_date >= current_date), 0) as active_users,
    (select min(s.end_date) from public.subscriptions s where s.company_id = c.id and s.end_date >= current_date) as next_end_date
from public.companies c
where exists (
    select 1 from public.deals d where d.company_id = c.id and d.stage = 'won' and d.archived_at is null
);

grant all on table public.customers_summary to anon;
grant all on table public.customers_summary to authenticated;
grant all on table public.customers_summary to service_role;

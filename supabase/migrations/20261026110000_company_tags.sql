create table public.company_tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

alter table public.company_tags enable row level security;

create policy "Enable read access for authenticated users" on public.company_tags for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.company_tags for insert to authenticated with check (true);
create policy "Company Tag Update Policy" on public.company_tags for update to authenticated using (true);
create policy "Company Tag Delete Policy" on public.company_tags for delete to authenticated using (true);

grant all on table public.company_tags to anon;
grant all on table public.company_tags to authenticated;
grant all on table public.company_tags to service_role;
grant all on sequence public.company_tags_id_seq to anon;
grant all on sequence public.company_tags_id_seq to authenticated;
grant all on sequence public.company_tags_id_seq to service_role;

alter table public.companies add column tags bigint[] not null default '{}';

create or replace view public.companies_summary with (security_invoker = on) as
select
    c.id,
    c.created_at,
    c.name,
    c.sector,
    c.size,
    c.linkedin_url,
    c.website,
    c.phone_number,
    c.address,
    c.zipcode,
    c.city,
    c.state_abbr,
    c.sales_id,
    c.context_links,
    c.country,
    c.description,
    c.revenue,
    c.tax_identifier,
    c.logo,
    count(distinct d.id) as nb_deals,
    count(distinct co.id) as nb_contacts,
    c.competitor,
    c.lead_source,
    c.tags
from public.companies c
    left join public.deals d on c.id = d.company_id
    left join public.contacts co on c.id = co.company_id
group by c.id;

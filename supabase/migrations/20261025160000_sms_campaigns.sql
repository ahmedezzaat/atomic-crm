create table public.sms_campaigns (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sender_id text not null default 'Kords',
    message text not null default '',
    audience jsonb not null default '{}'::jsonb,
    schedule_at timestamp with time zone,
    status text not null default 'draft',
    recipients integer not null default 0,
    sent_at timestamp with time zone,
    error text,
    sales_id bigint,
    constraint sms_campaigns_status_check check (status in ('draft', 'scheduled', 'sending', 'sent', 'failed'))
);

create table public.sms_messages (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    campaign_id bigint not null,
    company_id bigint,
    phone text not null,
    body text not null default '',
    status text not null default 'pending',
    provider_message_id text,
    error text,
    updated_at timestamp with time zone not null default now(),
    constraint sms_messages_status_check check (status in ('pending', 'sent', 'delivered', 'undelivered', 'failed'))
);

alter table public.sms_campaigns
    add constraint sms_campaigns_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.sms_messages
    add constraint sms_messages_campaign_id_fkey foreign key (campaign_id) references public.sms_campaigns(id) on update cascade on delete cascade;

alter table public.sms_messages
    add constraint sms_messages_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete set null;

create index sms_messages_campaign_id_idx on public.sms_messages (campaign_id);
create index sms_messages_provider_message_id_idx on public.sms_messages (provider_message_id);

create or replace trigger set_sms_campaign_sales_id_trigger
    before insert on public.sms_campaigns
    for each row execute function public.set_sales_id_default();

alter table public.sms_campaigns enable row level security;
alter table public.sms_messages enable row level security;

create policy "Enable read access for authenticated users" on public.sms_campaigns for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.sms_campaigns for insert to authenticated with check (true);
create policy "SMS Campaign Update Policy" on public.sms_campaigns for update to authenticated using (true);
create policy "SMS Campaign Delete Policy" on public.sms_campaigns for delete to authenticated using (true);
create policy "Enable read access for authenticated users" on public.sms_messages for select to authenticated using (true);

grant all on table public.sms_campaigns to authenticated;
grant all on table public.sms_campaigns to service_role;
grant select on table public.sms_messages to authenticated;
grant all on table public.sms_messages to service_role;
grant all on sequence public.sms_campaigns_id_seq to authenticated;
grant all on sequence public.sms_campaigns_id_seq to service_role;
grant all on sequence public.sms_messages_id_seq to service_role;

-- Campaign progress, derived from the per-recipient messages.
create or replace view public.sms_campaigns_summary with (security_invoker = on) as
select
    c.*,
    count(m.id) as nb_messages,
    count(m.id) filter (where m.status in ('sent', 'delivered')) as nb_sent,
    count(m.id) filter (where m.status = 'delivered') as nb_delivered,
    count(m.id) filter (where m.status in ('undelivered', 'failed')) as nb_failed
from public.sms_campaigns c
    left join public.sms_messages m on m.campaign_id = c.id
group by c.id;

grant all on table public.sms_campaigns_summary to authenticated;
grant all on table public.sms_campaigns_summary to service_role;

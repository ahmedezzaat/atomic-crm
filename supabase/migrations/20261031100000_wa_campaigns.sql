create table public.wa_campaigns (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    template_name text not null default '',
    template_language text not null default 'ar',
    with_name boolean not null default true,
    audience jsonb not null default '{}'::jsonb,
    daily_cap integer not null default 50,
    status text not null default 'draft',
    error text,
    sales_id bigint,
    constraint wa_campaigns_status_check check (status in ('draft', 'active', 'done')),
    constraint wa_campaigns_daily_cap_check check (daily_cap between 1 and 1000)
);

alter table public.wa_campaigns
    add constraint wa_campaigns_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.whatsapp_messages add column campaign_id bigint;
alter table public.whatsapp_messages
    add constraint whatsapp_messages_campaign_id_fkey foreign key (campaign_id) references public.wa_campaigns(id) on update cascade on delete set null;
create index whatsapp_messages_campaign_id_idx on public.whatsapp_messages (campaign_id);

create or replace trigger set_wa_campaign_sales_id_trigger
    before insert on public.wa_campaigns
    for each row execute function public.set_sales_id_default();

alter table public.wa_campaigns enable row level security;
create policy "Enable read access for authenticated users" on public.wa_campaigns for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.wa_campaigns for insert to authenticated with check (true);
create policy "WA Campaign Update Policy" on public.wa_campaigns for update to authenticated using (true);
create policy "WA Campaign Delete Policy" on public.wa_campaigns for delete to authenticated using (true);

grant all on table public.wa_campaigns to authenticated;
grant all on table public.wa_campaigns to service_role;
grant all on sequence public.wa_campaigns_id_seq to authenticated;
grant all on sequence public.wa_campaigns_id_seq to service_role;

-- Campaign progress, derived from the messages sent for it.
create or replace view public.wa_campaigns_summary with (security_invoker = on) as
select
    c.*,
    count(m.id) as nb_messages,
    count(m.id) filter (where m.status in ('sent', 'delivered', 'read')) as nb_sent,
    count(m.id) filter (where m.status in ('delivered', 'read')) as nb_delivered,
    count(m.id) filter (where m.status = 'read') as nb_read,
    count(m.id) filter (where m.status = 'failed') as nb_failed,
    count(distinct m.phone) filter (where exists (
        select 1 from public.whatsapp_messages r
        where r.phone = m.phone and r.direction = 'in' and r.created_at > m.created_at
    )) as nb_replied
from public.wa_campaigns c
    left join public.whatsapp_messages m on m.campaign_id = c.id and m.direction = 'out'
group by c.id;

grant all on table public.wa_campaigns_summary to authenticated;
grant all on table public.wa_campaigns_summary to service_role;

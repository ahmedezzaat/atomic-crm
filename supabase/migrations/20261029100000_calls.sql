create table public.calls (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    title text not null default '',
    company_id bigint,
    contact_id bigint,
    channel text not null,
    guest_key text not null,
    status text not null default 'scheduled',
    started_at timestamp with time zone,
    ended_at timestamp with time zone,
    sales_id bigint,
    constraint calls_status_check check (status in ('scheduled', 'active', 'ended')),
    constraint calls_guest_key_key unique (guest_key),
    constraint calls_channel_key unique (channel)
);

alter table public.calls
    add constraint calls_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete set null;

alter table public.calls
    add constraint calls_contact_id_fkey foreign key (contact_id) references public.contacts(id) on update cascade on delete set null;

alter table public.calls
    add constraint calls_sales_id_fkey foreign key (sales_id) references public.sales(id);

create index calls_company_id_idx on public.calls (company_id);

alter table public.calls enable row level security;

-- Staff only. Guests never touch this table: they join through the call_guest
-- function, which checks the secret guest_key.
create policy "Enable read access for authenticated users" on public.calls for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.calls for insert to authenticated with check (true);
create policy "Call Update Policy" on public.calls for update to authenticated using (true);
create policy "Call Delete Policy" on public.calls for delete to authenticated using (true);

grant all on table public.calls to authenticated;
grant all on table public.calls to service_role;
grant all on sequence public.calls_id_seq to authenticated;
grant all on sequence public.calls_id_seq to service_role;
